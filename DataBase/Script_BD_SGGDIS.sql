-- ============================================================

CREATE TABLE INS_ORDENANZA_PLAZO (
  ID_ORDENANZA_PLAZO  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_ORDENANZA         NUMBER NOT NULL,
  TIPO_PLAZO           VARCHAR2(10) NOT NULL,
  CANTIDAD             NUMBER,
