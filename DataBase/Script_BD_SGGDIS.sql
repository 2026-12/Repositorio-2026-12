-- Acta de Inspección General (HU-004 y sub-HU HU-006 a HU-011).
-- Es un acta administrativa por apartados, no un checklist puntuable
-- como INS_INSPECCION. INS_ACTA_GENERAL es la tabla principal (folio y
-- estado) y cada apartado del wizard vive en su propia tabla, relacionada
-- 1:1 con el acta: ID_ACTA es a la vez PK y FK, asi la BD garantiza una
-- sola fila por apartado y por acta. La fila de un apartado se crea la
-- primera vez que se guarda (autoguardado); si el apartado nunca se
-- guardo, no tiene fila. Las columnas de apartado son opcionales porque
-- se llenan de forma incremental. Sin ON DELETE CASCADE (igual que
-- INS_RESPUESTA): el backend borra las filas de los apartados antes que el acta.
-- ============================================================
CREATE TABLE INS_ACTA_GENERAL (
  ID_ACTA                       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NUMERO_ACTA                   VARCHAR2(20) NOT NULL,
  ESTADO                        VARCHAR2(20) DEFAULT 'EN_PROCESO' NOT NULL,
  FECHA_CREACION                DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_ACTA_GENERAL PRIMARY KEY (ID_ACTA),
  CONSTRAINT UQ_ACTA_GENERAL_NUMERO UNIQUE (NUMERO_ACTA),
  CONSTRAINT CK_ACTA_GENERAL_ESTADO CHECK (ESTADO IN ('EN_PROCESO','FINALIZADA'))
);

