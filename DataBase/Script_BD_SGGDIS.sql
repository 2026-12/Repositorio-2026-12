  MES_CUMPLIMIENTO     NUMBER,
  ANIO_CUMPLIMIENTO    NUMBER,
  HORA_CUMPLIMIENTO    VARCHAR2(5),

  CONSTRAINT PK_INS_ORDENANZA_PLAZO
    PRIMARY KEY (ID_ORDENANZA_PLAZO),

  CONSTRAINT FK_INS_ORDENANZA_PLAZO_ORDENANZA
    FOREIGN KEY (ID_ORDENANZA)
    REFERENCES INS_ORDENANZA (ID_ORDENANZA),

  CONSTRAINT UQ_INS_ORDENANZA_PLAZO
    UNIQUE (ID_ORDENANZA),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_TIPO
    CHECK (TIPO_PLAZO IN ('FECHA', 'HORAS', 'DIAS', 'MESES')),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_CANTIDAD
