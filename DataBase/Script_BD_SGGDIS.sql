           DIA_CUMPLIMIENTO BETWEEN 1 AND 31),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_MES
    CHECK (MES_CUMPLIMIENTO IS NULL OR
           MES_CUMPLIMIENTO BETWEEN 1 AND 12),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_ANIO
    CHECK (ANIO_CUMPLIMIENTO IS NULL OR
           ANIO_CUMPLIMIENTO BETWEEN 1900 AND 9999),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_HORA
    CHECK (
      HORA_CUMPLIMIENTO IS NULL OR
      REGEXP_LIKE(HORA_CUMPLIMIENTO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
    ),

  CONSTRAINT CK_INS_ORDENANZA_PLAZO_DATOS
    CHECK (
      (
        TIPO_PLAZO = 'FECHA'
        AND CANTIDAD IS NULL
        AND DIA_CUMPLIMIENTO IS NOT NULL
        AND MES_CUMPLIMIENTO IS NOT NULL
        AND ANIO_CUMPLIMIENTO IS NOT NULL
      )
      OR
      (
        TIPO_PLAZO IN ('HORAS', 'DIAS', 'MESES')
        AND CANTIDAD IS NOT NULL
        AND DIA_CUMPLIMIENTO IS NULL
        AND MES_CUMPLIMIENTO IS NULL
        AND ANIO_CUMPLIMIENTO IS NULL
        AND HORA_CUMPLIMIENTO IS NULL
      )
    )
);


