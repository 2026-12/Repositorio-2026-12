-- Apartado II: Información del Responsable durante la inspección (HU-007).
-- CARGO_RESPONSABLE guarda los codigos de los cargos seleccionados separados
-- por coma, ej. 'REPRESENTANTE_LEGAL,OTRO' (selección múltiple, mismo patron
-- que ACCIONES_SEGUIR del Apartado V).
CREATE TABLE INS_ACTA_RESPONSABLE (
  ID_ACTA                             NUMBER NOT NULL,
  NOMBRE_RESPONSABLE                  VARCHAR2(200),
  CARGO_RESPONSABLE                   VARCHAR2(200),
  CARGO_RESPONSABLE_OTRO              VARCHAR2(200),
  NUMERO_IDENTIFICACION_RESPONSABLE   VARCHAR2(30),
  CONSTRAINT PK_ACTA_RESPONSABLE PRIMARY KEY (ID_ACTA),
  CONSTRAINT FK_ACTA_RESPONSABLE_ACTA FOREIGN KEY (ID_ACTA) REFERENCES INS_ACTA_GENERAL (ID_ACTA),
  CONSTRAINT CK_ACTA_RESPONSABLE_CARGO CHECK (
    CARGO_RESPONSABLE IS NULL OR REGEXP_LIKE(CARGO_RESPONSABLE,
      '^(REPRESENTANTE_LEGAL|DENUNCIANTE|PRESIDENTE|DENUNCIADO|ENCARGADO|APODERADO|OTRO)(,(REPRESENTANTE_LEGAL|DENUNCIANTE|PRESIDENTE|DENUNCIADO|ENCARGADO|APODERADO|OTRO))*$')
  )
);

-- Apartado III: Motivo de la inspección (HU-008).
-- MOTIVO_INSPECCION guarda los codigos de los motivos seleccionados
-- separados por coma, ej. 'DENUNCIA,EMERGENCIA' (selección múltiple, mismo
-- patron que ACCIONES_SEGUIR del Apartado V).
CREATE TABLE INS_ACTA_MOTIVO (
  ID_ACTA                       NUMBER NOT NULL,
  MOTIVO_INSPECCION             VARCHAR2(200),
  MOTIVO_INSPECCION_OTRO        VARCHAR2(200),
  CONSTRAINT PK_ACTA_MOTIVO PRIMARY KEY (ID_ACTA),
  CONSTRAINT FK_ACTA_MOTIVO_ACTA FOREIGN KEY (ID_ACTA) REFERENCES INS_ACTA_GENERAL (ID_ACTA),
  CONSTRAINT CK_ACTA_MOTIVO_VALOR CHECK (
    MOTIVO_INSPECCION IS NULL OR REGEXP_LIKE(MOTIVO_INSPECCION,
      '^(PRIMERA_VEZ_PSF|SEGUIMIENTO|RENOVACION_PSF|DENUNCIA|LEY_9028_10066|EVENTO_MASIVO|EMERGENCIA|OTRO)(,(PRIMERA_VEZ_PSF|SEGUIMIENTO|RENOVACION_PSF|DENUNCIA|LEY_9028_10066|EVENTO_MASIVO|EMERGENCIA|OTRO))*$')
  )
);

-- Apartado IV: Hallazgos de la inspección (HU-009).
-- GUIAS_APLICABLES guarda los ID_GUIA (INS_GUIA) seleccionados separados
-- por coma, ej. '1,3'. No lleva FK porque es una lista; el backend valida
-- que cada id exista en INS_GUIA antes de guardar.
CREATE TABLE INS_ACTA_HALLAZGOS (
  ID_ACTA                       NUMBER NOT NULL,
  GUIAS_APLICABLES              VARCHAR2(200),
  HALLAZGOS                     VARCHAR2(4000),
  CONSTRAINT PK_ACTA_HALLAZGOS PRIMARY KEY (ID_ACTA),
  CONSTRAINT FK_ACTA_HALLAZGOS_ACTA FOREIGN KEY (ID_ACTA) REFERENCES INS_ACTA_GENERAL (ID_ACTA),
  CONSTRAINT CK_ACTA_HALLAZGOS_GUIAS CHECK (
    GUIAS_APLICABLES IS NULL OR REGEXP_LIKE(GUIAS_APLICABLES, '^[0-9]+(,[0-9]+)*$')
  )
);

-- Apartado V: Acciones a seguir (HU-010).
-- ACCIONES_SEGUIR guarda los codigos de las acciones seleccionadas
-- separados por coma, ej. 'ORDEN_SANITARIA,DECOMISO'. Los textos solo
-- tienen contenido si su accion (REPROGRAMACION / OTRO) esta seleccionada.
CREATE TABLE INS_ACTA_ACCIONES (
  ID_ACTA                       NUMBER NOT NULL,
  ACCIONES_SEGUIR               VARCHAR2(200),
  MOTIVO_REPROGRAMACION         VARCHAR2(400),
  ACCION_OTRO                   VARCHAR2(200),
  CONSTRAINT PK_ACTA_ACCIONES PRIMARY KEY (ID_ACTA),
  CONSTRAINT FK_ACTA_ACCIONES_ACTA FOREIGN KEY (ID_ACTA) REFERENCES INS_ACTA_GENERAL (ID_ACTA),
  CONSTRAINT CK_ACTA_ACCIONES_CODIGOS CHECK (
    ACCIONES_SEGUIR IS NULL OR REGEXP_LIKE(ACCIONES_SEGUIR,
      '^(CIERRE_CASO|ORDEN_SANITARIA|RETENCION|APOYO_TECNICO|DECOMISO|CLAUSURA|INFORME_TECNICO|INFORME_SANITARIO_TABACO|RETIRO_PSF|REPROGRAMACION|OTRO)(,(CIERRE_CASO|ORDEN_SANITARIA|RETENCION|APOYO_TECNICO|DECOMISO|CLAUSURA|INFORME_TECNICO|INFORME_SANITARIO_TABACO|RETIRO_PSF|REPROGRAMACION|OTRO))*$')
  )
);

-- Apartado VI: Cierre de la inspeccion (HU-011).
-- La hora de inicio se consulta de INS_ACTA_INFO_GENERAL.HORA_INICIO (no se
-- duplica). PERSONAS_PRESENTES guarda la lista dinamica de personas como un
-- arreglo JSON, ej.
-- '[{"nombreCompleto":"...","cargoInstitucion":"...","numeroIdentificacion":"...","firma":"..."}]'.
-- Es CLOB porque la cantidad de personas no tiene tope (VARCHAR2(4000)
-- alcanzaria solo para unas pocas personas con todos sus datos).
CREATE TABLE INS_ACTA_CIERRE (
  ID_ACTA                       NUMBER NOT NULL,
  PERSONAS_PRESENTES            CLOB,
  CONSTRAINT PK_ACTA_CIERRE PRIMARY KEY (ID_ACTA),
  CONSTRAINT FK_ACTA_CIERRE_ACTA FOREIGN KEY (ID_ACTA) REFERENCES INS_ACTA_GENERAL (ID_ACTA),
  CONSTRAINT CK_ACTA_CIERRE_PERSONAS CHECK (
    PERSONAS_PRESENTES IS NULL OR PERSONAS_PRESENTES IS JSON
  )
);

